function interpolate(template, params = {}) {
  return String(template).replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (params[key] === undefined || params[key] === null) {
      return '';
    }
    return String(params[key]);
  });
}

export function translate(language, key, params) {
  const lang = language === 'en' ? 'en' : 'fr';
  const template = STRINGS[lang][key] ?? STRINGS.fr[key] ?? key;
  const count = params?.count != null ? Number(params.count) : null;
  const plural = count != null && count > 1 ? 's' : '';
  const verb = lang === 'en'
    ? (count != null && count > 1 ? '' : 's')
    : (count != null && count > 1 ? 'nt' : '');
  return interpolate(template, {...params, plural, verb});
}

export function localeFor(language) {
  return language === 'en' ? 'en-US' : 'fr-FR';
}

export function ageRangeOptions(t) {
  return [
    ['under18', t('ageUnder18')],
    ['18-24', t('age1824')],
    ['25-34', t('age2534')],
    ['35-44', t('age3544')],
    ['45plus', t('age45plus')],
  ];
}

const LanguageContext = createContext({
  language: 'fr',
  locale: 'fr-FR',
  t: (key, params) => translate('fr', key, params),
  setLanguage: () => {},
});

export function LanguageProvider({language, setLanguage, children}) {
  const value = useMemo(() => {
    const lang = language === 'en' ? 'en' : 'fr';
    return {
      language: lang,
      locale: localeFor(lang),
      t: (key, params) => translate(lang, key, params),
      setLanguage,
    };
  }, [language, setLanguage]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useI18n() {
  return useContext(LanguageContext);
}
